const generatedColors = [
  '#d96767',
  '#dc8f55',
  '#d6b64c',
  '#8dbb58',
  '#51ae78',
  '#4db5a8',
  '#529fc8',
  '#687fd1',
  '#8c6dcc',
  '#b468c0',
  '#cc668e',
  '#a48a72',
];

function generatedColor(id: TobiasAspectId) {
  const hash = [...id].reduce(
    (total, character) => total + character.charCodeAt(0),
    0,
  );
  return colorOverrides[id] ?? generatedColors[hash % generatedColors.length];
}

export const tobiasAspects: Aspect[] = definitions.map(([id, components]) => ({
  id,
  color: generatedColor(id),
  icon: {id: icons[id]},
  components: components ? [components[0], components[1]] : null,
  opposite: opposites[id],
}));
